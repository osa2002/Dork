i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: localStorage.getItem("dorkq_lang") || "ar", // Default to Arabic (ar)
    fallbackLng: "en",
    interpolation: {
      escapeValue: false
    }
  });

// Handle text direction and language changes
i18n.on("languageChanged", (lng) => {
  localStorage.setItem("dorkq_lang", lng);
  const dir = (lng || "ar").startsWith("ar") ? "rtl" : "ltr";
  document.documentElement.dir = dir;
  document.documentElement.lang = lng;
  // Apply direction to the body element too for consistency
  document.body.dir = dir;
  document.body.style.direction = dir;
  if (dir === "rtl") {
    document.body.classList.remove("text-left");
    document.body.classList.add("text-right");
  } else {
    document.body.classList.remove("text-right");
    document.body.classList.add("text-left");
  }
});

// Initialize on load
const currentLng = i18n.language || "ar";
const initialDir = currentLng.startsWith("ar") ? "rtl" : "ltr";
document.documentElement.dir = initialDir;
document.documentElement.lang = currentLng;
document.body.dir = initialDir;
document.body.style.direction = initialDir;
if (initialDir === "rtl") {
  document.body.classList.add("text-right");
} else {
  document.body.classList.add("text-left");
}

export default i18n;
